-- SQL estándar (PostgreSQL y H2): sirve en desarrollo, pruebas y producción
CREATE TABLE proveedores (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc             VARCHAR(13)   NOT NULL UNIQUE,
    razon_social    VARCHAR(200)  NOT NULL,
    limite_credito  NUMERIC(12, 2),
    estado          VARCHAR(20)                -- enum guardado como texto
);

CREATE TABLE contratos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             VARCHAR(30)    NOT NULL UNIQUE,
    monto              NUMERIC(12, 2) NOT NULL,
    fecha_inicio       DATE           NOT NULL,
    fecha_vencimiento  DATE           NOT NULL,
    proveedor_id       BIGINT         NOT NULL REFERENCES proveedores (id)
);

CREATE TABLE categorias (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(255)  NOT NULL UNIQUE
);
-- Tabla intermedia de la relación @ManyToMany (Capítulo 15)
CREATE TABLE contrato_categoria (
    contrato_id   BIGINT  NOT NULL REFERENCES contratos (id),
    categoria_id  BIGINT  NOT NULL REFERENCES categorias (id),
    PRIMARY KEY (contrato_id, categoria_id)
);
-- Usuarios del sistema: password guarda el hash BCrypt, nunca la clave
CREATE TABLE usuarios (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(50)   NOT NULL UNIQUE,
    password  VARCHAR(100)  NOT NULL,
    rol       VARCHAR(20)   NOT NULL         -- ADMIN o GESTOR
);
